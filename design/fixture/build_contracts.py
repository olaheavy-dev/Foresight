def uid(prefix: str, seed: str) -> str:
    digest = hashlib.sha256(seed.encode()).digest()
    body = "".join(CROCKFORD[b % 32] for b in digest[:26])
    return f"{prefix}_01{body[:24]}"


def minor(pounds: float) -> int:
    return int(round(pounds * 100))


def money(pounds: float, ref: str | None = None, exact: bool = False) -> dict:
    m = minor(pounds)
    sign = "−" if m < 0 else ""
    if exact:
        disp = f"{sign}£{abs(m) / 100:,.2f}"
    else:
        disp = f"{sign}£{abs(round(pounds)):,.0f}"
    v = {"kind": "money", "minor": m if exact else minor(round(pounds)), "currency": "GBP",
         "display": disp, "precision": "exact" if exact else "rounded"}
    if ref:
        v["ref"] = ref
    return v


def pct(value_pct: float, ref: str | None = None, change: bool = False) -> dict:
    v = {"kind": "pct_change" if change else "percent", "value": round(value_pct / 100, 4),
         "display": (f"+{value_pct:.0f}%" if change and value_pct > 0 else f"{value_pct:.0f}%")}
    if ref:
        v["ref"] = ref
    return v


def dt(iso: str, ref: str | None = None) -> dict:
    d = date.fromisoformat(iso)
    v = {"kind": "date", "value": iso, "display": f"{d.day} {d.strftime('%b')} {d.year}"}
    if ref:
        v["ref"] = ref
    return v


# Answer skeleton (docs/08 §7a): fixed Overview slot order and one fixed tab set.
