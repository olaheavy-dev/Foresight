TABS = ("details", "recommendation", "transactions", "checked")


def overview(slot: str | None = None) -> dict:
    p = {"area": "overview"}
    if slot:
        p["slot"] = slot
    return p


def tab(name: str) -> dict:
    assert name in TABS, name
    return {"area": "tab", "tab": name}


def block(bid: str, btype: str, evidence: list[str], placement: dict, **fields) -> dict:
    if placement["area"] == "overview" and "slot" not in placement:
        placement = {**placement, "slot": SLOT_BY_TYPE.get(btype, "main_visual")}
    b = {"block_id": bid, "type": btype, "currency": "GBP", "placement": placement,
         "evidence": evidence, "actions": fields.pop("actions", [])}
    b.update(fields)
    return b


def write(name: str, plan: dict, response: dict) -> None:
    calc_ids = sorted({r.split("#")[0] for b in response["blocks"] for r in b.get("evidence", [])
                       if r.startswith("calc_")})
    fnd = sorted({r for b in response["blocks"] for r in b.get("evidence", []) if r.startswith("fnd_")})
    recs = sorted({r for b in response["blocks"] for r in b.get("evidence", []) if r.startswith("rec_")})
    response["provenance"] = {"calc_ids": calc_ids, "finding_ids": fnd, "recommendation_ids": recs}
    (OUT / name).write_text(json.dumps({"_note": NOTE, "plan": plan, "response": response},
                                       indent=1, ensure_ascii=False) + "\n")


