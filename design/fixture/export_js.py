"""Export the chart-relevant parts of fixture.json to design/hifi/assets/data.js."""
import json
from pathlib import Path

here = Path(__file__).parent
d = json.loads((here / "fixture.json").read_text())
keep = {k: d[k] for k in ("today", "as_of", "balance", "buffer", "salary_net", "paydays",
                          "cycles", "what_if", "end_of_march_all", "uncertainty", "lows",
                          "history", "weekly", "food_delivery", "daily_spend_model", "overall",
                          "delivery_pace_to_payday", "plan_cap_below_pace_pct", "rejected_cap_below_pace_pct")}
out = here.parent / "hifi" / "assets" / "data.js"
out.write_text("// Generated by design/fixture/export_js.py from fixture.json. Do not edit.\n"
               "window.FIXTURE = " + json.dumps(keep) + ";\n")
print("wrote", out)
