"""Regenerate the README's "Built" / "Not shipped (planned)" section from features.yaml.

The section between the STATUS markers is generated, never typed (docs/01 FR-86).
Run with --check in CI to fail when the committed README is out of date.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from backend.features import Feature, load_features

START = "<!-- STATUS:START (generated by tools/render_readme_status.py; do not edit) -->"
END = "<!-- STATUS:END -->"


def render(features: list[Feature]) -> str:
    built = [f for f in features if f.enabled]
    planned = [f for f in features if not f.enabled]
    lines = [START, "", "### Built", ""]
    lines += [f"- {f.title}" for f in built] or ["- Nothing yet: Foresight is in Stage 0."]
    lines += ["", "### Not shipped (planned)", ""]
    lines += [f"- Stage {f.stage}: {f.title}" for f in sorted(planned, key=lambda f: f.stage)]
    lines += ["", END]
    return "\n".join(lines)


def update(readme: str, block: str) -> str:
    if START not in readme or END not in readme:
        raise ValueError("README is missing the STATUS markers")
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--features", default="features.yaml")
    parser.add_argument("--readme", default="README.md")
    parser.add_argument("--check", action="store_true", help="fail if README is out of date")
    args = parser.parse_args(argv)

    path = Path(args.readme)
    current = path.read_text(encoding="utf-8")
    updated = update(current, render(load_features(args.features)))
    if args.check:
        if updated != current:
            print(
                "README status section is out of date; run tools/render_readme_status.py",
                file=sys.stderr,
            )
            return 1
        return 0
    path.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
