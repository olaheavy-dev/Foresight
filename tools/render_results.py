"""Regenerate the README's self-evaluation table from evals/results/latest.json (docs/09 §12, §15).

The section between the RESULTS markers is generated, never typed: no cherry-picking, and a null
result prints "—" and is never shown as met. Run with --check in CI to fail on drift.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from evals.headline import dig, headline

START = "<!-- RESULTS:START (generated by tools/render_results.py; do not edit) -->"
END = "<!-- RESULTS:END -->"

BASELINE_NAMES = {"B0": "flat", "B1": "repeat-30", "B2": "mean-flow", "B3": "calendar-only"}


def _f(value: Any, digits: int = 3) -> str:
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def _gbp(value: Any) -> str:
    return "—" if value is None else f"£{value:,.2f}"


def _met(summary: dict[str, Any], suite: str, *ids: str) -> str:
    """✓ when every listed target was measured and met, ✗ when any measured one failed, else —."""
    targets = {t["id"]: t for t in (summary.get("targets") or {}).get(suite, [])}
    found = [targets[i].get("met") for i in ids if i in targets]
    if any(m is False for m in found):
        return "✗"
    if found and all(m is True for m in found) and len(found) == len(ids):
        return "✓"
    return "—"


def _baseline(name: Any) -> str:
    return f"{name}-{BASELINE_NAMES[name]}" if name in BASELINE_NAMES else _f(name)


def render(summary: dict[str, Any]) -> str:
    h = headline(summary)
    s = summary.get("suites") or {}
    cov = h["forecast.coverage_by_dataset"] or {}
    cov_text = " · ".join(f"{_f(v)} ({k.split('-')[0]})" for k, v in cov.items()) or "—"
    sha = (summary.get("git_sha") or "")[:7] or "unknown"
    lines = [
        START,
        "",
        f"Run `{summary['run_id']}` · commit `{sha}` · {summary['timestamp_utc']} · mode: "
        f"{summary['mode']} (no model calls) · engine {summary['engine_version']} · generator "
        f"{summary['generator_version']} · seed {', '.join(str(x) for x in summary['seeds'])}",
        "",
        "Reproduce: `make eval` (every deterministic suite) or `make eval-fast` (< 60 s). Full "
        "report: `evals/results/<run>/report.md`. LLM arms (hybrid categorisation, Verifier, "
        "orchestration) arrive with Stage 2 and show as —.",
        "",
        "**Headline**",
        "",
        "| Area | Metric | Dataset | Foresight | Best baseline | Target | Met |",
        "|---|---|---|---|---|---|---|",
        f"| Categorisation | Accuracy · macro-F1 (rules-only) | P1+P2 test split "
        f"(n={_f(h['categorisation.n'])}) | {_f(h['categorisation.accuracy'])} · "
        f"{_f(h['categorisation.macro_f1'])} | majority class "
        f"{_f(h['categorisation.majority_accuracy'])} | hybrid ≥ 0.93 (Stage 2) | — |",
        f"| Forecast | MAE @30 d | P1 | {_gbp(h['forecast.mae30_gbp'])} | "
        f"{_baseline(h['forecast.best_baseline_30'])} {_gbp(h['forecast.best_baseline_mae30_gbp'])}"
        f" | skill vs repeat-30 ≥ 0.20 (got {_f(h['forecast.skill_vs_B1_30'])}) | "
        f"{_met(summary, 'E-FC', 'FC-skill-B1')} |",
        f"| Forecast | P10–P90 coverage (all h) | P1, P2, S4 | {cov_text} | — | 0.72–0.88 "
        f"(P1, P2) | {_met(summary, 'E-FC', 'FC-coverage-P1', 'FC-coverage-P2')} |",
        f"| Reconciliation | Corrupted CSVs caught | CSV-CORRUPT | "
        f"{_f(h['reconciliation.corrupt_detected'])}/{_f(h['reconciliation.corrupt_total'])} | — | "
        f"20/20 | {_met(summary, 'E-ING', 'ING-corrupt')} |",
        f"| Verifier | Bad proposals caught | — | {_f(h['verifier.catch_rate'])} | — | ≥ 0.95 "
        "| — |",
        "",
        "**All deterministic suites**",
        "",
        "| Suite | Gate | Results | Target misses |",
        "|---|---|---|---|",
    ]
    ing = dig(s, "ingestion", "csv_statement") or {}
    rows = {
        "E-ING": (
            f"table locator P/R {_f(dig(ing, 'table_locator', 'builtin_and_common', 'precision'))}"
            f"/{_f(dig(ing, 'table_locator', 'builtin_and_common', 'recall'))}; built-in profile "
            f"match {_f(dig(ing, 'builtin_profile', 'match_rate'))}; unseen C1–C4 heuristic-only "
            f"{_f(dig(ing, 'format_profile_unseen', 'heuristic_only', 'success'))}"
        ),
        "E-LOC": (
            f"currency detection {_f(dig(s, 'locales', 'currency_detection_acc'))}; number / date "
            f"format {_f(dig(s, 'locales', 'number_format_acc'))} / "
            f"{_f(dig(s, 'locales', 'date_order_acc'))}; minor units exact "
            f"{_f(dig(s, 'locales', 'minor_unit_exact'))}; H13 all clauses "
            f"{_f(dig(s, 'locales', 'h13', 'all_clauses_ok'))}"
        ),
        "E-CAT": (
            f"flow-class accuracy {_f(h['categorisation.flow_class_accuracy'])}; coverage@0.85 "
            f"{_f(dig(s, 'categorisation', 'arms', 'rules_only', 'coverage', '0.85', 'coverage'))}"
        ),
        "E-INC": (
            f"salaried P/R {_f(dig(s, 'income', 'salaried_precision'))}/"
            f"{_f(dig(s, 'income', 'salaried_recall'))}; amount ±2% "
            f"{_f(dig(s, 'income', 'amount_within_2pct'))}; payday rule "
            f"{_f(dig(s, 'income', 'payday_rule_ok'))}"
        ),
        "E-REC": (
            f"P/R {_f(dig(s, 'recurring', 'precision'))}/{_f(dig(s, 'recurring', 'recall'))}; "
            f"council-tax months exact {_f(dig(s, 'recurring', 'council_tax_months_exact'))}"
        ),
        "E-ANOM": (
            f"category trends: recall {_f(dig(s, 'anomalies', 'recall'))}, precision "
            f"{_f(dig(s, 'anomalies', 'precision'))}, false positives / persona-month "
            f"{_f(dig(s, 'anomalies', 'fp_per_persona_month_clean'))}"
        ),
        "E-FC": (
            f"MAE @7/30/60 d (P1) {_gbp(dig(s, 'forecast', 'by_horizon', '7', 'mae_gbp'))} / "
            f"{_gbp(dig(s, 'forecast', 'by_horizon', '30', 'mae_gbp'))} / "
            f"{_gbp(dig(s, 'forecast', 'by_horizon', '60', 'mae_gbp'))}; pay-cycle-low error "
            f"{_gbp(dig(s, 'forecast', 'pay_cycle_low_mae_gbp'))}; pinball (P1) "
            f"{_gbp(dig(s, 'forecast', 'pinball_gbp_by_dataset', 'P1-base'))}"
        ),
        "E-SIM": (
            f"properties SIM-1/2/3/6: {_f(dig(s, 'simulation', 'passed'))}/"
            f"{_f(dig(s, 'simulation', 'total'))} cases passed"
        ),
    }
    detail = summary.get("gate_detail") or {}
    for sid in summary.get("suites_run") or []:
        d = detail.get(sid, {})
        lines.append(
            f"| {sid} | {d.get('status', '—')} | {rows.get(sid, '—')} | "
            f"{', '.join(d.get('failed') or []) or '—'} |"
        )
    not_run = [sid for sid, d in detail.items() if d.get("rule") == "not run"]
    lines += ["", f"Not run yet: {', '.join(not_run) or 'none'}.", ""]
    lines += _forecast_arms(s)
    lines += [
        "**Where we fall short**",
        "",
    ]
    misses = [
        f"- {sid} {t['id']}: {t['label']} = {_f(t['value'])} (target {t['target']}, {t['dataset']})"
        for sid, targets in (summary.get("targets") or {}).items()
        for t in targets
        if t.get("stage1") and t.get("met") is False
    ]
    lines += misses or ["- No measured Stage 1 target missed."]
    lines += ["", END]
    return "\n".join(lines)


def _forecast_arms(s: dict[str, Any]) -> list[str]:
    """The E-FC arms: the headline simulates a user step, so the no-confirmation numbers are
    shown next to it (docs/09 §7)."""
    arms = dig(s, "forecast", "arms") or {}
    headline_arm = dig(s, "forecast", "headline_arm")
    if not arms or headline_arm not in arms:
        return []
    out = [
        f"**Forecast arms.** The headline forecast numbers come from the arm that "
        f"{arms[headline_arm]['note']}. "
        "Without that step:",
        "",
        "| Arm | Coverage P1 · P2 · S4 | MAE @30 d P1 · P2 · S4 | Pinball P1 · P2 · S4 |",
        "|---|---|---|---|",
    ]
    for name, arm in arms.items():
        cov = arm.get("coverage_by_dataset") or {}
        mae = arm.get("mae30_gbp_by_dataset") or {}
        pin = arm.get("pinball_gbp_by_dataset") or {}
        label = f"{name} (headline)" if name == headline_arm else name
        out.append(
            f"| {label} | {' · '.join(_f(v) for v in cov.values())} | "
            f"{' · '.join(_gbp(v) for v in mae.values())} | "
            f"{' · '.join(_gbp(v) for v in pin.values())} |"
        )
    return [*out, ""]


def update(readme: str, block: str) -> str:
    if START not in readme or END not in readme:
        raise ValueError("README is missing the RESULTS markers")
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", default="evals/results/latest.json")
    parser.add_argument("--readme", default="README.md")
    parser.add_argument("--check", action="store_true", help="fail if README is out of date")
    args = parser.parse_args(argv)

    summary = json.loads(Path(args.results).read_text(encoding="utf-8"))
    path = Path(args.readme)
    current = path.read_text(encoding="utf-8")
    updated = update(current, render(summary))
    if args.check:
        if updated != current:
            print(
                "README results section is out of date; run tools/render_results.py",
                file=sys.stderr,
            )
            return 1
        return 0
    path.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
