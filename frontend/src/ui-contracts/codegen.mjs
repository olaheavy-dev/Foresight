// Generates types.ts and guards.ts from the contracts JSON Schema (read from stdin).
// Run through `python tools/export_schemas.py [--check]`; never edit the outputs by hand.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const STALE_EXIT = 10; // distinct from a crash (1)
const here = dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes("--check");
const chunks = [];
for await (const chunk of process.stdin) chunks.push(chunk);
const schema = JSON.parse(Buffer.concat(chunks).toString("utf8"));
const BANNER = "// Generated by tools/export_schemas.py from backend/app/ui_contracts. Do not edit.\n";

// Property titles would become dozens of tiny aliases (Mode1, Mode2…); keep only the names of
// $defs, and drop `discriminator` (the oneOf it annotates already gives the union type).
function strip(node) {
  if (Array.isArray(node)) return node.map(strip);
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "title" || key === "discriminator" || key === "description") continue;
    if (key === "properties" || key === "$defs") {
      out[key] = Object.fromEntries(Object.entries(value).map(([k, v]) => [k, strip(v)]));
    } else {
      out[key] = strip(value);
    }
  }
  return out;
}

const defs = Object.fromEntries(
  Object.entries(schema.$defs).map(([name, def]) => [name, { ...strip(def), title: name }]),
);

// Pydantic inlines discriminated unions; name the shared ones so the TS reads like docs/08.
const signature = (node) => (node && Array.isArray(node.oneOf) ? JSON.stringify(node.oneOf) : undefined);
const NAMED_UNIONS = {
  Block: defs.AgentResponse.properties.blocks.items,
  BlockPlan: defs.ResponsePlan.properties.blocks.items,
  FollowUpAction: defs.AgentResponse.properties.follow_ups.items,
  FollowUpPlan: defs.ResponsePlan.properties.follow_ups.items,
  SpendingBreakdownChart: defs.AgentResponse.properties.blocks.items.oneOf.find((n) => n.oneOf),
  Placement: defs.Narrative.properties.placement,
  Segment: defs.Narrative.properties.segments.items,
  Value: defs.Metric.properties.value,
};
const bySignature = new Map(Object.entries(NAMED_UNIONS).map(([name, node]) => [signature(node), name]));
function nameUnions(node) {
  if (Array.isArray(node)) return node.map(nameUnions);
  if (node === null || typeof node !== "object") return node;
  const named = bySignature.get(signature(node));
  if (named) return { $ref: `#/$defs/${named}` };
  return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, nameUnions(v)]));
}
for (const [name, node] of Object.entries(NAMED_UNIONS)) {
  defs[name] = { oneOf: nameUnions(node.oneOf), title: name };
}
for (const name of Object.keys(defs)) {
  if (!(name in NAMED_UNIONS)) defs[name] = nameUnions(defs[name]);
}
const roots = schema["x-roots"];
const forTypes = {
  title: "UiContracts",
  type: "object",
  properties: Object.fromEntries(roots.map((r) => [r, { $ref: `#/$defs/${r}` }])),
  additionalProperties: false,
  $defs: defs,
};

const types = await compile(forTypes, "UiContracts", {
  bannerComment: BANNER,
  additionalProperties: false,
  unreachableDefinitions: true,
  ignoreMinAndMaxItems: true,
  format: true,
  style: { printWidth: 100 },
});

function refsIn(node, acc = new Set()) {
  if (Array.isArray(node)) node.forEach((n) => refsIn(n, acc));
  else if (node && typeof node === "object") {
    if (typeof node.$ref === "string") acc.add(node.$ref.replace("#/$defs/", ""));
    for (const [k, v] of Object.entries(node)) if (k !== "discriminator") refsIn(v, acc);
  }
  return acc;
}
const blockDefs = [...refsIn(schema.$defs.AgentResponse.properties.blocks.items.oneOf)];

const guard = (name) =>
  `export function is${name}(value: unknown): value is T.${name} {\n` +
  `  return validate("${name}", value).length === 0;\n}\n` +
  `export function check${name}(value: unknown): SchemaError[] {\n` +
  `  return validate("${name}", value);\n}\n`;

const guards =
  BANNER +
  `import type * as T from "./types";\n` +
  `import { validate, type SchemaError } from "./validate";\n\n` +
  `export const ROOT_TYPES = ${JSON.stringify(roots)} as const;\n` +
  `export const BLOCK_DEFS = ${JSON.stringify(blockDefs)} as const;\n\n` +
  [...roots, ...blockDefs].map(guard).join("\n");

// schema.json itself is written and compared by the Python side.
const outputs = { "types.ts": types, "guards.ts": guards };
let stale = 0;
for (const [file, content] of Object.entries(outputs)) {
  const path = join(here, file);
  if (check) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
      console.log(`frontend/src/ui-contracts/${file}`);
      stale += 1;
    }
  } else {
    writeFileSync(path, content);
    console.log(`Wrote frontend/src/ui-contracts/${file}`);
  }
}
process.exit(stale ? STALE_EXIT : 0);
